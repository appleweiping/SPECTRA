#!/usr/bin/env python3
"""Summarize strict public-config shards without mixing capability tiers.

The public adapters intentionally produce two kinds of receipts.  Source decks
without a matched corner contract are retained as TT-only capability evidence,
while a merged receipt with more than one verified PVT condition can be used
for PVT ranking.  This script reports both tiers and never upgrades a TT-only
receipt into a PVT result.
"""

from __future__ import annotations

import argparse
import glob
import json
import math
from pathlib import Path


def finite(value: object) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(float(value))


def fmt(value: object, digits: int = 4) -> str:
    if not finite(value):
        return "NA"
    return f"{float(value):.{digits}f}"


def load_paths(patterns: list[str]) -> list[Path]:
    paths: list[Path] = []
    for pattern in patterns:
        paths.extend(Path(item) for item in (glob.glob(pattern) or [pattern]))
    return sorted({path.resolve() for path in paths if path.exists()})


def aggregate_from_rows(rows: list[dict]) -> dict[str, dict[str, object]]:
    grouped: dict[str, list[dict]] = {}
    for row in rows:
        grouped.setdefault(str(row.get("method", "unknown")), []).append(row)
    output: dict[str, dict[str, object]] = {}
    for method, method_rows in sorted(grouped.items()):
        count = max(1, len(method_rows))
        pvt_values = [row.get("pvt", {}).get("mean_normalized_violation") for row in method_rows]
        wall_values = [row.get("wall_seconds") for row in method_rows]
        first_pass_values = [row.get("first_pass_simulations") for row in method_rows]
        output[method] = {
            "cells": len(method_rows),
            "tt_success": sum(bool(row.get("tt_pass")) for row in method_rows) / count,
            "pvt_success": sum(bool(row.get("pvt", {}).get("pvt_success")) for row in method_rows) / count,
            "mean_tt_violation": sum(float(row.get("tt_violation", float("nan"))) for row in method_rows) / count,
            "mean_pvt_violation": sum(float(v) for v in pvt_values if finite(v)) / max(1, sum(finite(v) for v in pvt_values)),
            "mean_wall_seconds": sum(float(v) for v in wall_values if finite(v)) / max(1, sum(finite(v) for v in wall_values)),
            "mean_simulations_to_first_pass": sum(float(v) for v in first_pass_values if finite(v)) / max(1, sum(finite(v) for v in first_pass_values)),
        }
    return output


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", nargs="*", default=[
        "results/public_v5_*_merged.json",
        "results/public_v3_*_merged.json",
        "results/public_x1_v3_*_merged.json",
    ])
    parser.add_argument("--output", type=Path, default=Path("results/public_v2_summary.md"))
    parser.add_argument("--json-output", type=Path, default=None)
    args = parser.parse_args()

    paths = load_paths(args.input)
    if not paths:
        raise SystemExit("no merged public-v2 receipts found")

    records: list[dict] = []
    for path in paths:
        payload = json.loads(path.read_text(encoding="utf-8"))
        rows = payload.get("rows", [])
        aggregate = payload.get("aggregate") or aggregate_from_rows(rows)
        conditions = payload.get("pvt_conditions")
        eligible = bool(payload.get("complete")) and bool(payload.get("ranking_eligible"))
        track = str(rows[0].get("task") or rows[0].get("track_id") or path.stem) if rows else path.stem
        records.append({
            "file": path.name,
            "track": track,
            "pvt_conditions": conditions,
            "complete": bool(payload.get("complete")),
            "ranking_eligible": eligible,
            "errors": list(payload.get("errors", [])),
            "aggregate": aggregate,
        })

    lines = [
        "# Public benchmark summary",
        "",
        "This report is generated by `scripts/summarize_public_v2.py` from strict merged receipts.",
        "Each cell uses 300 simulator evaluations and 12 LLM calls. A receipt with one source condition is TT-only capability evidence and is excluded from PVT ranking. Only a complete receipt with more than one verified condition and `ranking_eligible=true` enters the PVT table.",
        "",
        "## Receipt audit",
        "",
        "| Receipt | Task | PVT conditions | Complete | PVT ranking eligible | Audit errors |",
        "|---|---|---:|:---:|:---:|---:|",
    ]
    for record in records:
        lines.append(
            f"| `{record['file']}` | `{record['track']}` | {record['pvt_conditions'] if record['pvt_conditions'] is not None else 'NA'} | "
            f"{'yes' if record['complete'] else 'no'} | {'yes' if record['ranking_eligible'] else 'no'} | {len(record['errors'])} |"
        )

    lines += [
        "",
        "## Method metrics",
        "",
        "| Receipt | Method | Cells | TT success | PVT success | Mean TT violation | Mean PVT violation | Mean first-pass simulations | Mean wall seconds | Tier |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---|",
    ]
    exported: list[dict] = []
    for record in records:
        tier = "PVT ranking" if record["ranking_eligible"] else ("TT-only capability" if record["pvt_conditions"] == 1 else "incomplete")
        for method, values in sorted(record["aggregate"].items()):
            row = {
                "receipt": record["file"],
                "track": record["track"],
                "method": method,
                "tier": tier,
                **values,
            }
            exported.append(row)
            lines.append(
                f"| `{record['file']}` | `{method}` | {values.get('cells', 'NA')} | {fmt(values.get('tt_success'))} | "
                f"{fmt(values.get('pvt_success'))} | {fmt(values.get('mean_tt_violation'))} | {fmt(values.get('mean_pvt_violation'))} | "
                f"{fmt(values.get('mean_simulations_to_first_pass'), 2)} | {fmt(values.get('mean_wall_seconds'), 2)} | {tier} |"
            )

    lines += [
        "",
        "## Interpretation contract",
        "",
        "* TT-only rows preserve real simulator outcomes and efficiency measurements, but they do not support a PVT claim because the source task exposes only one matched condition.",
        "* Capability receipts for source repositories are reported separately from matched SPECTRA-vs-AnaFlow ranking. A successful default-point simulation is not treated as a sizing win.",
        "* Any negative endpoint, missing metric, or incomplete shard remains in the receipt and denominator. This summary does not drop difficult tasks or upgrade non-finite values.",
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    if args.json_output:
        args.json_output.parent.mkdir(parents=True, exist_ok=True)
        args.json_output.write_text(json.dumps({"schema": "spectra-public-v2-summary/v1", "receipts": records, "rows": exported}, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps({"receipts": len(records), "rows": len(exported), "pvt_ranking_receipts": sum(record["ranking_eligible"] for record in records)}))


if __name__ == "__main__":
    main()
