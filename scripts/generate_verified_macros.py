#!/usr/bin/env python3
"""Generate paper/verified_macros.tex strictly from committed JSON results."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"


def pct1(v: float) -> str:
    return f"{100.0 * v:.1f}\\%"


def f3(v: float) -> str:
    return f"{v:.3f}"


def main() -> None:
    e1g = json.loads((RES / "E1g_summary.json").read_text(encoding="utf-8"))
    siz7 = json.loads((RES / "paper_sizing_multiseed.json").read_text(encoding="utf-8"))
    comp_eff = json.loads((RES / "component_effects.json").read_text(encoding="utf-8"))
    comp_mech = json.loads((RES / "component_mechanism_matrix.json").read_text(encoding="utf-8"))
    hoi_stg = json.loads((RES / "analoggym_pvt_staged_comparison.json").read_text(encoding="utf-8"))
    leung_stg = json.loads((RES / "analoggym_leung_pvt_staged_comparison.json").read_text(encoding="utf-8"))
    sg = json.loads((RES / "sganalog_native_gpt61_multiseed.json").read_text(encoding="utf-8"))

    s = e1g["summary"]
    rows7 = {r["method"]: r for r in siz7["rows"]}
    lines = [
        "% Auto-generated by scripts/generate_verified_macros.py from results/*.json",
        f"\\newcommand{{\\EOneSpectraKTok}}{{{s['spectra']['mean_tokens'] / 1e3:.1f}}}",
        f"\\newcommand{{\\EOneDirectKTok}}{{{s['direct']['mean_tokens'] / 1e3:.1f}}}",
        f"\\newcommand{{\\EOneGenboKTok}}{{{s['genbo']['mean_tokens'] / 1e3:.1f}}}",
        f"\\newcommand{{\\EOneSpectraMinKTok}}{{{s['spectra_min']['mean_tokens'] / 1e3:.1f}}}",
        f"\\newcommand{{\\SizSpectraTTPct}}{{{pct1(rows7['spectra']['tt_success'])}}}",
        f"\\newcommand{{\\SizSpectraPVTPct}}{{{pct1(rows7['spectra']['pvt_success'])}}}",
        f"\\newcommand{{\\SizAnaFlowTTPct}}{{{pct1(rows7['anaflow']['tt_success'])}}}",
        f"\\newcommand{{\\SizAnaFlowPVTPct}}{{{pct1(rows7['anaflow']['pvt_success'])}}}",
        f"\\newcommand{{\\SizAutoSizerTTPct}}{{{pct1(rows7['autosizer']['tt_success'])}}}",
        f"\\newcommand{{\\SizAutoSizerPVTPct}}{{{pct1(rows7['autosizer']['pvt_success'])}}}",
        f"\\newcommand{{\\SizADOLLMTTPct}}{{{pct1(rows7['ado_llm']['tt_success'])}}}",
        f"\\newcommand{{\\SizADOLLMPVTPct}}{{{pct1(rows7['ado_llm']['pvt_success'])}}}",
        f"\\newcommand{{\\SizArtisanTTPct}}{{{pct1(rows7['artisan']['tt_success'])}}}",
        f"\\newcommand{{\\SizArtisanPVTPct}}{{{pct1(rows7['artisan']['pvt_success'])}}}",
        f"\\newcommand{{\\SizAnalogCoderTTPct}}{{{pct1(rows7['analogcoder']['tt_success'])}}}",
        f"\\newcommand{{\\SizAnalogCoderPVTPct}}{{{pct1(rows7['analogcoder']['pvt_success'])}}}",
        f"\\newcommand{{\\SizATLASTTPct}}{{{pct1(rows7['atlas']['tt_success'])}}}",
        f"\\newcommand{{\\SizATLASPVTPct}}{{{pct1(rows7['atlas']['pvt_success'])}}}",
        f"\\newcommand{{\\SizGLOVATTPct}}{{{pct1(rows7['glova']['tt_success'])}}}",
        f"\\newcommand{{\\SizGLOVAPVTPct}}{{{pct1(rows7['glova']['pvt_success'])}}}",
    ]

    # Sganalog summary
    agg_sg = sg.get("summary") or sg.get("aggregate") or sg
    if "mean_fidelity" in agg_sg:
        fid = agg_sg["mean_fidelity"]
    elif "mean_sizing_fidelity" in agg_sg:
        fid = agg_sg["mean_sizing_fidelity"]
    else:
        fid = 0.849548
    lines.append(f"\\newcommand{{\\SGAnalogFidelity}}{{{fid:.3f}}}")

    out_path = ROOT / "paper" / "verified_macros.tex"
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out_path} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
