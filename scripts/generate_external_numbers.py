#!/usr/bin/env python3
"""Generate receipt-derived macros used by the external SIZ7g paper table."""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def fmt(value: float) -> str:
    return f"{value:.4f}".rstrip("0").rstrip(".")


def main() -> None:
    data = json.loads((ROOT / "results/paper_sizing_multiseed.json").read_text(encoding="utf-8"))
    rows = {row["method"]: row for row in data["rows"]}
    gate = json.loads((ROOT / "results/xsota_gate_audit.json").read_text(encoding="utf-8"))
    counts = {
        "receipts_observed": gate["receipts_observed"],
        "comparable_strata": gate["comparable_strata"],
        "uncovered_strata": gate["uncovered_strata"],
        "strict_all_endpoint_leads": gate["diagnostic_summary"]["comparable_strict_positive_all_endpoints"],
    }
    aliases = {
        "spectra": "SizSpectra", "analogcoder": "SizAnalogCoder", "ado_llm": "SizADOLLM",
        "anaflow": "SizAnaFlow", "artisan": "SizArtisan", "autosizer": "SizAutoSizer",
        "atlas": "SizATLAS", "glova": "SizGLOVA",
    }
    lines = ["% generated by scripts/generate_external_numbers.py from immutable receipts"]
    for method, alias in aliases.items():
        row = rows[method]
        lines.extend([
            f"\\newcommand{{\\{alias}TT}}{{{fmt(row['tt_success'])}}}",
            f"\\newcommand{{\\{alias}PVT}}{{{fmt(row['pvt_success'])}}}",
            f"\\newcommand{{\\{alias}TTViol}}{{{fmt(row['mean_violation_score'])}}}",
            f"\\newcommand{{\\{alias}PVTViol}}{{{fmt(row['mean_pvt_violation_score'])}}}",
        ])
    hoi = json.loads((ROOT / "results/analoggym_xyce_robust_merged.json").read_text(encoding="utf-8"))["aggregate"]
    leung = json.loads((ROOT / "results/analoggym_leung_xyce_robust_merged.json").read_text(encoding="utf-8"))["aggregate"]
    sganalog = json.loads((ROOT / "results/sganalog_xyce_ac_probe.json").read_text(encoding="utf-8"))
    h_spec, h_af = hoi["spectra"], hoi["anaflow_cleanroom"]
    l_spec, l_af = leung["spectra"], leung["anaflow_cleanroom"]
    lines.extend([
        f"\\newcommand{{\\SizTasks}}{{{data['n_tasks']}}}",
        f"\\newcommand{{\\SizSeeds}}{{{len(data['seeds'])}}}",
        f"\\newcommand{{\\SizCells}}{{{rows['spectra']['cells_observed']}}}",
        f"\\newcommand{{\\GateReceipts}}{{{counts['receipts_observed']}}}",
        f"\\newcommand{{\\GateComparable}}{{{counts['comparable_strata']}}}",
        f"\\newcommand{{\\GateUncovered}}{{{counts['uncovered_strata']}}}",
        f"\\newcommand{{\\GateStrictLeads}}{{{counts['strict_all_endpoint_leads']}}}",
        f"\\newcommand{{\\XyceHoiTT}}{{{fmt(h_spec['tt_success'])}}}",
        f"\\newcommand{{\\XyceHoiPVT}}{{{fmt(h_spec['pvt_success'])}}}",
        f"\\newcommand{{\\XyceHoiTTViol}}{{{fmt(h_spec['mean_tt_violation'])}}}",
        f"\\newcommand{{\\XyceHoiPVTViol}}{{{fmt(h_spec['mean_pvt_violation'])}}}",
        f"\\newcommand{{\\XyceHoiAnaTT}}{{{fmt(h_af['tt_success'])}}}",
        f"\\newcommand{{\\XyceHoiAnaPVT}}{{{fmt(h_af['pvt_success'])}}}",
        f"\\newcommand{{\\XyceHoiAnaTTViol}}{{{fmt(h_af['mean_tt_violation'])}}}",
        f"\\newcommand{{\\XyceHoiAnaPVTViol}}{{{fmt(h_af['mean_pvt_violation'])}}}",
        f"\\newcommand{{\\XyceLeungTT}}{{{fmt(l_spec['tt_success'])}}}",
        f"\\newcommand{{\\XyceLeungPVT}}{{{fmt(l_spec['pvt_success'])}}}",
        f"\\newcommand{{\\XyceLeungTTViol}}{{{fmt(l_spec['mean_tt_violation'])}}}",
        f"\\newcommand{{\\XyceLeungPVTViol}}{{{fmt(l_spec['mean_pvt_violation'])}}}",
        f"\\newcommand{{\\XyceAnaLeungTT}}{{{fmt(l_af['tt_success'])}}}",
        f"\\newcommand{{\\XyceAnaLeungPVT}}{{{fmt(l_af['pvt_success'])}}}",
        f"\\newcommand{{\\XyceAnaLeungTTViol}}{{{fmt(l_af['mean_tt_violation'])}}}",
        f"\\newcommand{{\\XyceAnaLeungPVTViol}}{{{fmt(l_af['mean_pvt_violation'])}}}",
        f"\\newcommand{{\\SGAnalogTasks}}{{{sganalog['task_count']}}}",
        f"\\newcommand{{\\SGAnalogFailures}}{{{sganalog['status_counts'].get('failed', 0)}}}",
    ])
    with (ROOT / "paper/external_numbers.tex").open("w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
